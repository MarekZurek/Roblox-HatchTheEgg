"""Generate transport-action reference tables. No prices or odds are calibrated here."""
from pathlib import Path
import argparse, json
ROOT=Path(__file__).resolve().parents[1]
def lua(v):
 if isinstance(v,dict):return '{'+','.join('['+json.dumps(str(k))+']='+lua(x) for k,x in v.items())+'}'
 if isinstance(v,list):return '{'+','.join(lua(x) for x in v)+'}'
 return json.dumps(v,ensure_ascii=True)
def load(name):return json.loads((ROOT/'docs/reference_data'/name).read_text(encoding='utf-8'))
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
 eggs=load('infrastructure.json')['eggs'];epic=load('research.json')['epic']
 data={'calendar':load('rewards.json')['calendar'],
       'epic':{e['id']:{'maxLevel':e['maxLevel'],'finalLevelPriceGE':e['prices'][-1]} for e in epic},
       'trophies':{str(e['index']):{'se':e['trophySoulEggRewards'],'ge':e['trophyGoldenEggRewards'],'pe':e['trophyProphecyEggRewards']} for e in eggs}}
 text='--!nocheck\n-- Generated by tools/generate_action_catalog.py; REFERENCE_ONLY, not a balance approval.\nreturn '+lua(data)+'\n'
 target=ROOT/'src/server/ActionReferenceData.luau'
 if args.check:assert target.read_text(encoding='utf-8')==text,'Action reference data is stale'
 else:target.write_text(text,encoding='utf-8')
 print('Action reference tables: PASS')
if __name__=='__main__':main()
