"""Independent stdlib oracle for NumericCodec v1; no gameplay/balance inputs."""
import random
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "tests/numeric/reference_vectors.luau"
RNG = random.Random(0x48544501)
MAX = (1 << 64) - 1
SAFE = (1 << 53) - 1


def q(text):
    return '"' + str(text) + '"'


def bits(number):
    return struct.pack("<d", number).hex()


def main():
    boundaries = [0, 1, 9, 10, (1 << 32) - 1, 1 << 32, (1 << 32) + 1,
                  SAFE - 1, SAFE, SAFE + 1, SAFE + 2, SAFE + 3,
                  (1 << 63) - 1, 1 << 63, MAX - 1, MAX]
    integers = boundaries + [RNG.getrandbits(64) for _ in range(400)]
    # Explicit nearest-even ties at every integer precision transition.
    integers += [((1 << p) + (1 << (p - 53)) + d)
                 for p in range(53, 64) for d in (-1, 0, 1)]
    raw_floats = [0, 1 << 63, 1, (1 << 63) | 1, (1 << 52) - 1,
                  1 << 52, 0x7FEFFFFFFFFFFFFF, 0xFFEFFFFFFFFFFFFF]
    raw_floats += [RNG.getrandbits(64) for _ in range(3000)]
    floats = []
    for raw in raw_floats:
        if ((raw >> 52) & 2047) == 2047:
            continue
        value = struct.unpack("<d", raw.to_bytes(8, "little"))[0]
        floats.append((raw.to_bytes(8, "little").hex(), repr(value)))
    for value in [0.1, 1.66e67, 1.90e81, 2**53, 1e-300]:
        floats.append((bits(value), repr(value)))
    pairs = [(a, b) for a in boundaries for b in boundaries]
    pairs += [(RNG.getrandbits(64), RNG.getrandbits(64)) for _ in range(500)]
    lines = ["-- Generated by tools/generate_numeric_vectors.py; Python int + struct oracle.",
             "-- Fixed seed 0x48544501. TEST ONLY; no balance or production configuration.",
             "return {", "\tfloats = {"]
    for raw, decimal in floats:
        lines.append(f"\t\t{{ {q(raw)}, {q(decimal)} }},")
    lines += ["\t},", "\tintegers = {"]
    for n in integers:
        exact = int(float(n)) == n
        lines.append("\t\t{ " + ", ".join([q(n), str(n >> 32), str(n & 0xFFFFFFFF),
                     q(bits(float(n))), str(exact).lower(), str(n <= SAFE).lower()]) + " },")
    lines += ["\t},", "\tpairs = {"]
    for a, b in pairs:
        add = q(a + b) if a + b <= MAX else "false"
        sub = q(a - b) if a >= b else "false"
        cmp = (a > b) - (a < b)
        lines.append(f"\t\t{{ {q(a)}, {q(b)}, {add}, {sub}, {cmp} }},")
    lines += ["\t},", "}", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Generated {len(floats)} float / {len(integers)} uint64 / {len(pairs)} pair vectors")


if __name__ == "__main__":
    main()
