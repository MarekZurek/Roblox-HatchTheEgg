"""Generate the INTERNAL_TEST_ONLY server catalog from unchanged reference JSON.

Run from any directory. --check compares bytes without writing. No network or engine.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def luau(value):
    if isinstance(value, dict):
        return "{" + ",".join("[" + json.dumps(k) + "]=" + luau(v) for k, v in value.items()) + "}"
    if isinstance(value, list):
        return "{" + ",".join(luau(v) for v in value) + "}"
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=True)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return format(value, ".17g")
    raise ValueError(f"Unsupported data type {type(value)}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    paths = [ROOT / "docs/reference_data" / f"{name}.json" for name in ("research", "infrastructure")]
    research, infrastructure = [json.loads(p.read_text(encoding="utf-8")) for p in paths]
    for source in (research, infrastructure):
        assert source["status"] == "REFERENCE_ONLY" and not source["productionConfigurationApproved"]
    common_ids = [r["id"] for r in research["common"]]
    common = {}
    for row in research["common"]:
        assert len(row["prices"]) == row["maxLevel"]
        assert len(row["effectsByLevel"]) == row["maxLevel"] + 1
        common[row["id"]] = {key: row[key] for key in ("id", "tier_raw", "maxLevel", "prices", "effectsByLevel")}
    epic_ids = [r["id"] for r in research["epic"]]
    epic = {}
    for row in research["epic"]:
        assert len(row["prices"]) == row["maxLevel"]
        assert len(row["effectsByLevel"]) == row["maxLevel"] + 1
        epic[row["id"]] = {key: row[key] for key in ("id", "tier_raw", "maxLevel", "prices", "effectsByLevel")}
    data = {
        "status": "INTERNAL_TEST_ONLY", "sourceStatus": "REFERENCE_ONLY",
        "productionConfigurationApproved": False,
        "sourceSha256": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in paths},
        "tierThresholds": research["tierThresholds"],
        "commonIds": common_ids,
        "common": common,
        "epicIds": epic_ids,
        "epic": epic,
        "egg": {k: infrastructure["eggs"][0][k] for k in ("index", "name", "value")},
        "eggs": [{k: r[k] for k in ("index", "name", "value")} for r in infrastructure["eggs"]],
        "habitats": [{k: r[k] for k in ("index", "name", "capacity", "prices")} for r in infrastructure["habitats"]],
        "vehicles": [{k: r[k] for k in ("index", "name", "capacity", "prices")} for r in infrastructure["vehicles"]],
    }
    content = "--!strict\n-- GENERATED by tools/generate_catalog.py. INTERNAL_TEST_ONLY; no production approval.\nreturn " + luau(data) + "\n"
    target = ROOT / "src/server/CatalogRegistry/Data.luau"
    if args.check:
        if not target.exists() or target.read_bytes() != content.encode():
            raise SystemExit("Catalog data is stale")
        print("Catalog generator check PASS")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content.encode())
        print("Generated", target.relative_to(ROOT))


if __name__ == "__main__":
    main()
